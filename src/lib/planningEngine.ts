import { addDays, format, parseISO } from 'date-fns';
import type { AiContext, PlanDraft } from '@/types/api';
import type { PendingAction, Task } from '@/types/models';
import type { Locale, Priority } from '@/types/enums';
import { detectConflicts } from './recurrence';
import { formatInZone, fromZoneTime } from './timezone';
import { makeId } from './utils';
import { findFreeSlots } from './assistantEngine';

/**
 * 本地规划引擎（AI 网关未部署时的降级核心）。
 * 纯函数：按优先级/截止时间排序未完成任务，填入用户时区的空闲时段，
 * 产出 create_event 草案（专注时段）。绝不写库、绝不覆盖已有课程。
 */

export type PlanMode = 'day' | 'reschedule';

const PRIORITY_WEIGHT: Record<Priority, number> = {
  urgent: 4,
  high: 3,
  medium: 2,
  low: 1,
};

/** 默认专注时长（分钟）与上下限 */
const DEFAULT_DURATION = 60;
const MIN_DURATION = 30;
const MAX_DURATION = 120;
/** 两个专注块之间的休息（分钟） */
const BREAK_MINUTES = 10;
/** 重新规划覆盖的未来天数 */
const RESCHEDULE_DAYS = 7;

const COPY = {
  'zh-CN': {
    focus: (title: string) => `专注：${title}`,
    focusDesc: (title: string) => `由智能规划生成，对应任务「${title}」`,
    daySummary: (n: number, hours: number) => `已为今天安排 ${n} 个专注时段（共 ${hours} 小时），按优先级与截止时间排序。`,
    dayEmpty: '今天没有可安排的任务或空闲时段，可先到「任务」页添加待办。',
    reSummary: (n: number, days: number, hours: number) => `已在未来 ${days} 天安排 ${n} 个专注时段（共 ${hours} 小时），优先处理逾期与高优先级任务。`,
    reEmpty: '暂无未完成任务需要重新规划。',
    unscheduled: (n: number) => `${n} 个任务未能排入空闲时段，可稍后重试或手动安排。`,
    conflict: '部分时段与已有日程重叠，请确认前留意。',
  },
  'en-US': {
    focus: (title: string) => `Focus: ${title}`,
    focusDesc: (title: string) => `Generated by Smart Planning for task "${title}"`,
    daySummary: (n: number, hours: number) => `Scheduled ${n} focus block(s) today (~${hours}h), sorted by priority and due date.`,
    dayEmpty: 'No tasks or free slots to plan today. Add a to-do on the Tasks page first.',
    reSummary: (n: number, days: number, hours: number) => `Scheduled ${n} focus block(s) over the next ${days} days (~${hours}h), prioritising overdue and high-priority tasks.`,
    reEmpty: 'No pending tasks need rescheduling.',
    unscheduled: (n: number) => `${n} task(s) could not fit into a free slot; retry later or arrange manually.`,
    conflict: 'Some slots overlap existing events — please review before confirming.',
  },
} as const;

function pad(n: number): string {
  return String(n).padStart(2, '0');
}

/** 把某时区日历日的"分钟偏移"转成 UTC ISO */
function minutesToUtc(dateStr: string, minutesOfDay: number, timezone: string): string {
  const h = Math.floor(minutesOfDay / 60);
  const m = minutesOfDay % 60;
  return fromZoneTime(`${dateStr}T${pad(h)}:${pad(m)}:00`, timezone).toISOString();
}

/** "HH:mm" → 当日分钟数 */
function hhmmToMinutes(s: string): number {
  const [h, m] = s.split(':').map(Number);
  return h * 60 + m;
}

/** 任务时长（分钟），限制在 30–120 之间 */
function durationOf(task: Task): number {
  const raw = typeof task.estimated_minutes === 'number' && task.estimated_minutes > 0
    ? task.estimated_minutes
    : DEFAULT_DURATION;
  return Math.max(MIN_DURATION, Math.min(MAX_DURATION, Math.round(raw / 15) * 15));
}

/** 按优先级（紧急>高>中>低）→ 截止时间（越近越前）排序 */
export function rankTasks(tasks: Task[]): Task[] {
  return [...tasks].sort((a, b) => {
    const byPriority = PRIORITY_WEIGHT[b.priority] - PRIORITY_WEIGHT[a.priority];
    if (byPriority !== 0) return byPriority;
    const ad = a.due_at ? new Date(a.due_at).getTime() : Infinity;
    const bd = b.due_at ? new Date(b.due_at).getTime() : Infinity;
    if (ad !== bd) return ad - bd;
    return a.title.localeCompare(b.title);
  });
}

interface Allocation {
  actions: PendingAction[];
  placedIds: Set<string>;
  totalMinutes: number;
}

/**
 * 把任务填入某日的空闲时段（贪心：优先级高的先占靠前的空闲）。
 * 只使用 findFreeSlots 返回的空闲段，因此不会与已有课程重叠。
 */
function allocateDay(
  tasks: Task[],
  dateStr: string,
  ctx: AiContext,
  locale: Locale,
  placed: Set<string>,
): Allocation {
  const actions: PendingAction[] = [];
  let totalMinutes = 0;
  if (tasks.length === 0) return { actions, placedIds: placed, totalMinutes };

  const slots = findFreeSlots(ctx, dateStr, MIN_DURATION);
  for (const slot of slots) {
    if (placed.size >= tasks.length) break;
    let cursor = hhmmToMinutes(slot.start);
    const slotEnd = hhmmToMinutes(slot.end);

    for (const task of tasks) {
      if (placed.has(task.id)) continue;
      const dur = durationOf(task);
      if (cursor + dur > slotEnd) continue;

      const startAt = minutesToUtc(dateStr, cursor, ctx.timezone);
      const endAt = minutesToUtc(dateStr, cursor + dur, ctx.timezone);
      const title = COPY[locale].focus(task.title);
      const conflicts = detectConflicts(
        { start_at: startAt, end_at: endAt, all_day: false },
        ctx.events,
      ).map((e) => e.title);

      actions.push({
        id: makeId(),
        kind: 'create_event',
        payload: {
          title,
          description: COPY[locale].focusDesc(task.title),
          location: null,
          start_at: startAt,
          end_at: endAt,
          all_day: false,
          category_id: task.category_id ?? null,
          category_name: undefined,
          timezone: ctx.timezone,
          recurrence: null,
          source_task_id: task.id,
        },
        description: `${title} · ${formatInZone(startAt, 'MM-dd HH:mm', ctx.timezone)}–${formatInZone(endAt, 'HH:mm', ctx.timezone)}`,
        conflicts,
      });
      placed.add(task.id);
      totalMinutes += dur;
      cursor += dur + BREAK_MINUTES;
    }
  }
  return { actions, placedIds: placed, totalMinutes };
}

/** 待规划任务集合：day=今天到期/逾期/无截止；reschedule=全部未完成任务 */
function candidateTasks(ctx: AiContext, mode: PlanMode): Task[] {
  const pending = ctx.tasks.filter((t) => !t.is_completed);
  if (mode === 'reschedule') return pending;
  const dayEnd = new Date(`${ctx.date}T23:59:59Z`).getTime();
  return pending.filter((t) => !t.due_at || new Date(t.due_at).getTime() <= dayEnd);
}

/**
 * 生成计划草案。planDay 只看今天；reschedule 覆盖未来 7 天。
 * 返回 PlanDraft（summary/actions/conflicts），调用方负责展示与确认。
 */
export function buildPlan(ctx: AiContext, mode: PlanMode, locale: Locale): PlanDraft {
  const c = COPY[locale];
  const tasks = rankTasks(candidateTasks(ctx, mode));
  if (tasks.length === 0) {
    return {
      summary: mode === 'day' ? c.dayEmpty : c.reEmpty,
      actions: [],
      conflicts: [],
    };
  }

  const placed = new Set<string>();
  let actions: PendingAction[] = [];
  let totalMinutes = 0;

  if (mode === 'day') {
    const day = allocateDay(tasks, ctx.date, ctx, locale, placed);
    actions = day.actions;
    totalMinutes = day.totalMinutes;
  } else {
    for (let i = 0; i < RESCHEDULE_DAYS; i += 1) {
      if (placed.size >= tasks.length) break;
      const dateStr = format(addDays(parseISO(ctx.date), i), 'yyyy-MM-dd');
      const day = allocateDay(tasks, dateStr, ctx, locale, placed);
      actions = actions.concat(day.actions);
      totalMinutes += day.totalMinutes;
    }
  }

  const hours = Math.round((totalMinutes / 60) * 10) / 10;
  const summary = actions.length === 0
    ? (mode === 'day' ? c.dayEmpty : c.reEmpty)
    : mode === 'day'
      ? c.daySummary(actions.length, hours)
      : c.reSummary(actions.length, RESCHEDULE_DAYS, hours);

  const conflicts = actions.flatMap((a) => a.conflicts);
  const unscheduled = tasks.length - placed.size;
  const notes: string[] = [];
  if (conflicts.length > 0) notes.push(c.conflict);
  if (unscheduled > 0) notes.push(c.unscheduled(unscheduled));

  return {
    summary: notes.length ? `${summary}\n${notes.join(' ')}` : summary,
    actions,
    conflicts,
  };
}

/** 本地规划主入口（别名，语义化） */
export function planDay(ctx: AiContext, locale: Locale): PlanDraft {
  return buildPlan(ctx, 'day', locale);
}

/** 本地重新规划主入口（别名，语义化） */
export function reschedulePending(ctx: AiContext, locale: Locale): PlanDraft {
  return buildPlan(ctx, 'reschedule', locale);
}
